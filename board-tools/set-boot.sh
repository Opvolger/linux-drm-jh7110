#!/bin/bash
# Usage: board-tools/set-boot.sh              show which kernel /boot.scr boots
#        board-tools/set-boot.sh <release>    e.g. 7.4.0-rc1-jh7110 or 6.12.74+deb13+1-riscv64
#
# The VisionFive 2 boots through U-Boot `bootflow scan`, which finds /boot.scr on mmc 0:1
# (the eMMC root fs). GRUB is installed but not used. This script writes a fresh /boot.cmd
# for <release> and compiles it into /boot.scr (backup: /boot.scr.bak-<old release>).
# Debian names its kernel /boot/vmlinux-<rel>, a kernel from `make bindeb-pkg` is
# /boot/vmlinuz-<rel>; both are an uncompressed Image here, which `booti` can boot.
#
# Recovery when a kernel hangs: power-cycle, interrupt U-Boot (board-tools/catch.py), and
# type the load/booti lines of the stock kernel by hand (see the plan document).
set -euo pipefail
BOARD=${BOARD:-opvolger@192.168.2.33}
DTB=starfive/jh7110-starfive-visionfive-2-v1.3b.dtb
ARGS=${BOOTARGS:-root=/dev/mmcblk0p1 rw rootwait}

cur=$(ssh "$BOARD" "dd if=/boot.scr bs=72 skip=1 2>/dev/null | grep -o 'initrd.img-[^ ]*' | head -1" | sed 's/^initrd.img-//')
echo "current (boot.scr): $cur"
[ $# -gt 0 ] || exit 0
new=$1

kernel=$(ssh "$BOARD" "for k in /boot/vmlinuz-$new /boot/vmlinux-$new; do [ -f \$k ] && echo \$k && break; done")
[ -n "$kernel" ] || { echo "no /boot/vmlinu[xz]-$new on the board" >&2; exit 1; }
ssh "$BOARD" "test -f /usr/lib/linux-image-$new/$DTB && test -f /boot/initrd.img-$new" ||
	{ echo "dtb or initrd of $new missing on the board" >&2; exit 1; }

ssh "$BOARD" "sudo tee /boot.cmd >/dev/null" <<EOF
# Generated by board-tools/set-boot.sh (linux-drm-jh7110). Compile: mkimage -C none -A riscv -T script -d /boot.cmd /boot.scr
load mmc 0:1 \${kernel_addr_r} $kernel
load mmc 0:1 \${fdt_addr_r} /usr/lib/linux-image-$new/$DTB
load mmc 0:1 \${ramdisk_addr_r} /boot/initrd.img-$new
setenv bootargs '$ARGS'
booti \${kernel_addr_r} \${ramdisk_addr_r}:\${filesize} \${fdt_addr_r}
EOF
ssh "$BOARD" "sudo cp /boot.scr /boot.scr.bak-$cur && cd / && sudo mkimage -C none -A riscv -T script -d boot.cmd boot.scr >/dev/null && cat /boot.cmd"
